// Writes public/third-party-licenses.txt: the licences of the code shipped inside 3D Assembler
// (bundled into the web page and the desktop app). Run after changing a dependency:
//   node scripts/third-party.cjs
const fs = require('fs');
const path = require('path');

const licenceOf = (pkg) => {
  const dir = fs.realpathSync(path.join(process.cwd(), 'node_modules', pkg));
  const file = fs.readdirSync(dir).find((f) => /^licen[cs]e/i.test(f));
  const version = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8')).version;
  return { version, text: fs.readFileSync(path.join(dir, file), 'utf8').trim() };
};

